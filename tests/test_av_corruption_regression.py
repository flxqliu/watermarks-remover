def _minimal_png_with_text_chunk(text: bytes) -> bytes:
    sig = b"\x89PNG\r\n\x1a\n"

    def chunk(tag: bytes, payload: bytes) -> bytes:
        import zlib

        return (
            struct.pack(">I", len(payload))
            + tag
            + payload
            + struct.pack(">I", zlib.crc32(tag + payload))
        )

    ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    idat_payload = bytes([0, 255, 0, 0])
    import zlib as _zlib

    idat = _zlib.compress(idat_payload)
    return (
        sig
        + chunk(b"IHDR", ihdr)
        + chunk(b"tEXt", b"Comment\x00" + text)
        + chunk(b"IDAT", idat)
        + chunk(b"IEND", b"")
    )


def test_png_cleaning_unaffected_by_this_patch(tmp_path):
    src = tmp_path / "tagged.png"
    src.write_bytes(_minimal_png_with_text_chunk(AI_COMMENT.encode()))
    dest = tmp_path / "tagged.clean.png"

    result = clean_image(src, dest, strip_all_metadata=True)

    assert AI_COMMENT.encode() not in dest.read_bytes()
    assert result["still_has_ai_metadata"] is False


def test_markdown_cleaning_unaffected_by_this_patch(tmp_path):
    src = tmp_path / "doc.md"
    src.write_text(f"# Title\n\n<!-- {AI_COMMENT} -->\nBody text.\n", encoding="utf-8")
    dest = tmp_path / "doc.clean.md"

    result = clean_container(src, dest, fmt="markdown")

    cleaned_text = dest.read_text(encoding="utf-8")
    assert "Body text." in cleaned_text
