# ---------------------------------------------------------------------------
# The anti-corruption guard itself: prove it actually blocks, not just that
# real media happens to clean successfully.
# ---------------------------------------------------------------------------


@requires_ffmpeg
def test_guard_blocks_and_leaves_original_untouched_when_cleaning_would_corrupt(
    tmp_path, monkeypatch
):
    """Simulate a remux that produces garbage (any future regression in the
    remux path would look like this) and confirm clean_av refuses to write
    dest and raises instead of returning "success"."""
    import av_meta

    src = tmp_path / "faststart.mp4"
    _make_mp4(src, faststart=True)

    def _broken_remux(data, **_kwargs):
        return b"not a real container" * 20, ["simulated corruption"]

    monkeypatch.setattr(av_meta, "_remux_mp4_ffmpeg", _broken_remux)

    dest = tmp_path / "should_not_exist.mp4"
    with pytest.raises(ValueError, match="integrity check"):
        av_meta.clean_av(src, dest, strip_all_metadata=True)

    assert not dest.exists()
    assert not dest.with_name(dest.name + ".verify-tmp").exists()
    # Original is a plain read -- clean_av never opens *src* for writing.
    assert _decodable(src)


